#!/usr/bin/env node
/*
 * Regenerates test-onyx/modules.js. Run after adding or removing a file in src/:
 *
 *     node test-onyx/gen-modules.js
 *
 * Splits src/ into the modules a browser can actually import and the ones that
 * cannot resolve because they import a package that is not converted and not
 * checked out (enyo-ilib). all-modules.html reports those separately,
 * so a genuine failure there is never hidden behind an expected one.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const AVAILABLE = ['enyo', 'layout'];   // packages the import map can point at today

function walk (dir, out) {
	out = out || [];
	for (const e of fs.readdirSync(dir, {withFileTypes: true}).sort((a, b) => a.name < b.name ? -1 : 1)) {
		const p = path.join(dir, e.name);
		if (e.isDirectory()) walk(p, out);
		else if (e.name.endsWith('.js')) out.push(path.relative(ROOT, p));
	}
	return out;
}

const files = walk(path.join(ROOT, 'src'));

// Direct unresolvable (bare, non-enyo) specifiers per file.
const direct = {}, deps = {};
for (const f of files) {
	direct[f] = [];
	deps[f] = [];
	const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
	for (const m of src.matchAll(/^import(?:\s[^;\n]*from)?\s*['"]([^'"]+)['"]\s*;/gm)) {
		const spec = m[1];
		if (spec.startsWith('.')) {
			const t = path.relative(ROOT, path.resolve(path.dirname(path.join(ROOT, f)), spec));
			if (files.indexOf(t) !== -1) deps[f].push(t);
		} else if (AVAILABLE.indexOf(spec.split('/')[0]) === -1) {
			direct[f].push(spec);
		}
	}
}

// Propagate: importing a blocked module blocks you too.
const why = {};
for (const f of files) if (direct[f].length) why[f] = direct[f].slice();
let grew = true;
while (grew) {
	grew = false;
	for (const f of files) {
		if (why[f]) continue;
		for (const d of deps[f]) {
			if (why[d]) { why[f] = why[d].slice(); grew = true; break; }
		}
	}
}

const modules = files.filter(f => !why[f]).map(f => '../' + f);
const blocked = files.filter(f => why[f]).map(f => ({path: '../' + f, missing: why[f]}));

fs.writeFileSync(path.join(__dirname, 'modules.js'),
	'// Generated by gen-modules.js. Do not edit.\n' +
	'export const modules = ' + JSON.stringify(modules, null, 1) + ';\n\n' +
	'// Cannot be imported in a browser: these reach for a package that has not\n' +
	'// been converted to ES modules and is not checked out beside onyx.\n' +
	'export const blocked = ' + JSON.stringify(blocked, null, 1) + ';\n');

console.log(modules.length + ' importable, ' + blocked.length + ' blocked');
